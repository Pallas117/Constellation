/**
 * Score the L1 structure detectors on the GAU-154 holdout set:
 *   npm run replay:holdout            print the scorecard; exit 1 if it differs from the committed one
 *   npm run replay:holdout -- --update   rewrite backend/replay/golden/holdout-scorecard.json
 *                                     and docs/L1_STRUCTURES_HOLDOUT.md
 * Offline: reads the cached archives (npm run replay:fetch -- <holdout id>).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { HOLDOUT_EVENTS } from "../../backend/replay/holdout.js";
import { holdoutScorecard } from "../../backend/replay/holdout-score.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const SCORECARD = join(ROOT, "backend/replay/golden/holdout-scorecard.json");
const REPORT = join(ROOT, "docs/L1_STRUCTURES_HOLDOUT.md");

const fmt = (x: number | null) => (x === null ? "–" : `${x > 0 ? "+" : ""}${x} min`);

function report(card: ReturnType<typeof holdoutScorecard>): string {
  const t = card.totals;
  const rows = card.scores.map((s) => {
    const event = HOLDOUT_EVENTS.find((e) => e.id === s.id)!;
    const shock = s.shock ? `${s.shock.hit ? "hit" : "**miss**"} (${fmt(s.shock.arrivalErrorMin)})` : "none expected";
    const icme = s.icme ? `${s.icme.hit ? "hit" : "**miss**"} (${fmt(s.icme.startErrorMin)})` : "–";
    const falses = [...s.falseShocks.map((x) => `shock ${x.slice(5, 16)}`), ...s.falseIcmes.map((x) => `ICME ${x.slice(5, 16)}`)];
    return `| ${s.id} | ${event.title} | ${shock} | ${icme} | ${falses.join(", ") || "–"} | ${s.fieldOnly.map((x) => x.slice(5, 16)).join(", ") || "–"} |`;
  });
  return `# L1 structure detectors: holdout scorecard (GAU-154)

Generated by \`npm run replay:holdout -- --update\`. Do not edit by hand.

The detectors (\`backend/physics/l1-structures.ts\`) were never tuned on these windows. The events and
the scoring rules were pre-registered on GAU-154 on 2026-10-21, before any of this data was fetched or
scored (\`backend/replay/holdout.ts\`, \`backend/replay/holdout-score.ts\`). The catalogue is the
Richardson & Cane ICME list, https://izw1.caltech.edu/ACE/ASC/DATA/level3/icmetable2.htm (revised 23 July 2026).
L1 data: NOAA SWPC real-time solar wind as archived by NASA CCMC iSWA.

- **Shocks:** ${t.shocks.hit} of ${t.shocks.expected} hit (arrival at Earth within 30 min of the sudden commencement); ${t.shocks.falseAlarms} false alarm(s).
- **ICMEs:** ${t.icmes.hit} of ${t.icmes.expected} hit (start within 2 h); ${t.icmes.falseAlarms} false alarm(s).
- **Quiet days:** ${t.quietDayFalseAlarms} false alarm(s) over ${t.quietDays} days.

| Window | What | Shock (arrival error) | ICME (start error) | False alarms (UTC, at L1) | Field-only (UTC) |
|---|---|---|---|---|---|
${rows.join("\n")}

A false alarm is scored against the ICME catalogue only. A shock on a quiet day can still be real (a
stream interface is not in the list), so each is listed for checking, not hidden.

## Inside each catalogued ICME

The detector's inputs over the listed ICME interval, as far as each window reaches. A candidate
needs Bt > 8 nT with T/T_exp < 0.5 or beta < 0.1, held for 4 h. This explains misses; it isn't
a score, and the thresholds aren't changed on this set.

| Window | Minutes | Median T/T_exp | Median beta | Median Bt (nT) | T/T_exp < 0.5 | beta < 0.1 | Bt > 8 nT | ICME |
|---|---|---|---|---|---|---|---|---|
${card.scores
  .filter((s) => s.insideIcme)
  .map((s) => {
    const d = s.insideIcme!;
    const pct = (x: number | null) => (x === null ? "–" : `${Math.round(x * 100)} %`);
    const v = (x: number | null) => (x === null ? "–" : String(x));
    return `| ${s.id} | ${d.minutes} | ${v(d.medianTemperatureRatio)} | ${v(d.medianProtonBeta)} | ${v(d.medianBtNt)} | ${pct(d.shareLowTemperature)} | ${pct(d.shareLowBeta)} | ${pct(d.shareStrongField)} | ${s.icme?.hit ? "hit" : "miss"} |`;
  })
  .join("\n")}
`;
}

{
  const card = holdoutScorecard();
  const json = `${JSON.stringify(card, null, 2)}\n`;
  if (process.argv.includes("--update")) {
    writeFileSync(SCORECARD, json);
    writeFileSync(REPORT, report(card));
    console.log(`wrote ${SCORECARD} and ${REPORT}`);
  } else {
    console.log(JSON.stringify(card.totals, null, 2));
    let committed = "";
    try {
      committed = readFileSync(SCORECARD, "utf8");
    } catch {
      // no scorecard yet
    }
    if (committed !== json) {
      console.error("scorecard differs from the committed one; if intended, rerun with --update");
      process.exit(1);
    }
  }
}
